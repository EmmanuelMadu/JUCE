#!/usr/bin/env python3
"""Generate src/dsp/GrandTable.cpp from the measurements and the pack recipe.

  make_table.py <analysis.pkl> <measure.pkl> <recipe.json> <GrandTable.cpp>
"""
import os, sys, json, pickle
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import numpy as np
from make_pack import midi_to_name, ROOTS, HARM_ROOTS, ENV_T, bright_corner


def isotonic(y):
    """Pool-adjacent-violators: closest non-decreasing sequence."""
    y = list(map(float, y))
    blocks = [[v, 1] for v in y]
    i = 0
    while i < len(blocks) - 1:
        if blocks[i][0] > blocks[i + 1][0] + 1e-12:
            tot = blocks[i][0] * blocks[i][1] + blocks[i + 1][0] * blocks[i + 1][1]
            cnt = blocks[i][1] + blocks[i + 1][1]
            blocks[i:i + 2] = [[tot / cnt, cnt]]
            i = max(i - 1, 0)
        else:
            i += 1
    out = []
    for v, c in blocks:
        out += [v] * c
    return out


def main():
    an = pickle.load(open(sys.argv[1], 'rb'))
    part = pickle.load(open(sys.argv[2], 'rb'))['part']
    rec = json.load(open(sys.argv[3]))
    outp = sys.argv[4]
    files = rec['files']
    assert len(files) == len(an) == 641
    idx = {f['dst']: i for i, f in enumerate(files)}
    A = {a['dst']: a for a in an}
    db = lambda v: 20 * np.log10(max(v, 1e-12))

    # ---- tuning and string stiffness per sampled note
    cents, Bs, Fs = [], [], []
    for m in ROOTS:
        ps = [part['%sv%d.flac' % (midi_to_name(m), k)] for k in (8, 12, 15)]
        cents.append(float(np.median([p['cents'] for p in ps])))
        Bs.append(float(np.median([p['B'] for p in ps])))
        Fs.append(float(np.median([p['F'] for p in ps])))
    # the top notes have too few partials for a reliable stiffness: follow the
    # trend of the octaves below (log B is close to a straight line in the key)
    hi = [i for i, m in enumerate(ROOTS) if 72 <= m <= 96]
    c = np.polyfit([ROOTS[i] for i in hi], np.log([Bs[i] for i in hi]), 1)
    for i, m in enumerate(ROOTS):
        if m > 96:
            Bs[i] = float(np.exp(np.polyval(c, m)))

    # ---- the partials as they really are: a stiff-string formula is only the trend; every
    # partial sits a few cents off it, and it is the real frequencies that decide which
    # strings answer which.  Measured value where at least two strike strengths agree,
    # the formula otherwise.
    NP = 20
    parts, measured = [], 0
    for i, m in enumerate(ROOTS):
        ps = [part['%sv%d.flac' % (midi_to_name(m), k)] for k in (8, 12, 15)]
        row = []
        for n in range(1, NP + 1):
            fit = n * Fs[i] * np.sqrt(1 + Bs[i] * n * n)
            got = sorted(p['partials'][n][0] for p in ps if n in p['partials'])
            val = fit
            if len(got) >= 2:
                med = got[len(got) // 2] if len(got) == 3 else 0.5 * (got[0] + got[1])
                spread = 1200 * np.log2(got[-1] / got[0])
                if spread < 3.0 and abs(1200 * np.log2(med / fit)) < 12.0:
                    val = med
                    measured += 1
            row.append(float(val))
        parts.append(row)
        f_et = 440.0 * 2 ** ((m - 69) / 12.0)
        cents[i] = float(1200 * np.log2(row[0] / f_et))          # the first partial as it sounds
    print('partials taken from measurement: %d of %d' % (measured, NP * len(ROOTS)))

    # ---- loudness order and smooth top level
    notes = []
    for i, m in enumerate(ROOTS):
        lay = [A['n%03d_v%02d' % (m, k)] for k in range(1, 17)]
        lay.sort(key=lambda a: a['lk200'])
        br = isotonic([a['bright'] for a in lay])
        notes.append({'m': m, 'lay': lay, 'bright': br})
    top_raw = np.array([0.5 * (n['lay'][15]['lk200'] + n['lay'][14]['lk200']) for n in notes])
    med = top_raw.copy()
    for i in range(1, 29):
        med[i] = np.median(top_raw[i - 1:i + 2])
    top = med.copy()
    for i in range(1, 29):
        top[i] = 0.25 * med[i - 1] + 0.5 * med[i] + 0.25 * med[i + 1]

    L = []
    w = L.append
    w('// Generated by tools/grand/make_table.py -- do not edit.')
    w('// Measurements of the Salamander Grand Piano V3 (Alexander Holm, CC BY 3.0).')
    w('#include "GrandTable.h"')
    w('')
    w('namespace hk {')
    w('')
    w('const float kGrandEnvTime[kGrandEnvPoints] = { %s };' % ', '.join('%gf' % t for t in ENV_T))
    w('')
    w('const GrandFile kGrandFile[kGrandFiles] = {')
    for f in files:
        frames = f['end'] - f['start']
        scale = 1.0 / (f['gain'] * 8388608.0)
        w('  { "%s", %du, %.9gf, 0x%sull },' % (f['dst'], frames, scale, f['sum']))
    w('};')
    w('')
    w('const GrandNote kGrandNote[kGrandRoots] = {')
    for i, n in enumerate(notes):
        m = n['m']
        f1 = parts[i][0]
        w('  { %d, %.3ff, %.5ff, %.6gf, %.3ff, %.1ff,   // %s' % (m, cents[i], f1, Bs[i], top[i], bright_corner(m), midi_to_name(m)))
        w('    { %s }, {' % ', '.join('%.4ff' % v for v in parts[i]))
        for a, b in zip(n['lay'], n['bright']):
            ref = db(a['rms300'])
            env = [db(v) - ref if v == v else float('nan') for v in a['env']]
            for j in range(len(env)):
                if env[j] != env[j]:
                    step = min(env[j - 1] - env[j - 2], -3.0) if j >= 2 else -6.0
                    env[j] = max(env[j - 1] + step, -140.0)
            w('    { %d, %.2ff, %.2ff, { %s } },' % (idx[a['dst']], a['lk200'], b, ', '.join('%.1ff' % v for v in env)))
        w('  } },')
    w('};')
    w('')
    w('const GrandTail kGrandTail[3][kGrandTailRoots] = {')
    for tag in range(3):
        w('  { ' + ', '.join('{ %d, %.2ff }' % (idx['tail%d_%03d' % (tag, m)], A['tail%d_%03d' % (tag, m)]['lk1000']) for m in HARM_ROOTS) + ' },')
    w('};')
    w('')
    w('const uint16_t kGrandRel[88] = { %s };' % ', '.join(str(idx['rel_%03d' % (21 + k)]) for k in range(88)))
    w('const float kGrandRelLevel[88] = { %s };' % ', '.join('%.2ff' % A['rel_%03d' % (21 + k)]['lk200'] for k in range(88)))
    w('const uint16_t kGrandPedal[4] = { %s };' % ', '.join(str(idx[nm]) for nm in ('pedal_down1', 'pedal_down2', 'pedal_up1', 'pedal_up2')))
    w('')
    w('}  // namespace hk')
    open(outp, 'w').write('\n'.join(L) + '\n')
    print('roots: note cents  B        top(raw->smooth)  softest  range')
    for i, n in enumerate(notes):
        print('%-4s %+6.1f %.2e  %6.1f -> %6.1f   %6.1f  %5.1f' % (midi_to_name(n['m']), cents[i], Bs[i], top_raw[i], top[i],
              n['lay'][0]['lk200'], n['lay'][15]['lk200'] - n['lay'][0]['lk200']))
    rl = [A['rel_%03d' % (21 + k)]['lk200'] for k in range(88)]
    print('rel lk200 median %.1f min %.1f max %.1f' % (np.median(rl), min(rl), max(rl)))
    for tag in range(3):
        print('tail set', tag, 'loudness over 1 s:', ' '.join('%.0f' % A['tail%d_%03d' % (tag, m)]['lk1000'] for m in HARM_ROOTS))
    print('pedal lk200:', ' '.join('%.1f' % A[nm]['lk200'] for nm in ('pedal_down1', 'pedal_down2', 'pedal_up1', 'pedal_up2')))


if __name__ == '__main__':
    main()
